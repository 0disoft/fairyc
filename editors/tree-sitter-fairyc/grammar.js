// Editor parser only. spec/grammar/stage0.ebnf remains the compiler contract.
const list = rule => seq(rule, repeat(seq(',', rule)), optional(','));
module.exports = grammar({
 name: 'fairyc',
 word: $ => $.identifier,
 extras: $ => [/[ \t\r\n\uFEFF]/, $.line_comment, $.block_comment],
 externals: $ => [$.block_comment],
 conflicts: $ => [[$._statement, $._expression], [$._expression,$.record_expression], [$._expression,$.generic_call_expression,$.record_expression]],
 rules: {
  source_file: $ => seq($.module_declaration, repeat($.import_declaration), repeat($._item)),
  module_declaration: $ => seq('module', $.path, ';'),
  import_declaration: $ => seq('import', $.path, 'as', $.identifier, ';'),
  _item: $ => seq(repeat($.attribute), optional('pub'), choice($.constant_declaration,$.static_assert_declaration,$.state_declaration,$.struct_declaration,$.resource_declaration,$.enum_declaration,$.function_declaration,$.foreign_function_declaration)),
  attribute: $ => seq('@', $.path, optional(seq('(',optional(list(choice($.path,$.number,$.string))),')'))),
  constant_declaration: $ => seq('const',$._type,field('name',$.identifier),'=',$._expression,';'),
  static_assert_declaration: $ => seq('static_assert','(',$._expression,')',';'),
  state_declaration: $ => seq('state','{',repeat($.state_field),'}'),
  state_field: $ => choice(seq('cell',$._type,$.identifier,';'),seq('map',$._type,$._type,$.identifier,';')),
  struct_declaration: $ => seq('struct',field('name',$.identifier),optional($.type_parameters),'{',repeat($.field_declaration),'}'),
  resource_declaration: $ => seq('resource',field('name',$.identifier),optional($.type_parameters),'{',repeat($.field_declaration),optional($.cleanup_declaration),'}'),
  field_declaration: $ => seq(optional('pub'),$._type,field('name',$.identifier),';'),
  cleanup_declaration: $ => seq(repeat($.attribute),'cleanup',$.block),
  enum_declaration: $ => seq('enum',field('name',$.identifier),'{',repeat($.enum_variant),'}'),
  enum_variant: $ => seq(field('name',$.identifier),optional(seq('{',repeat($.field_declaration),'}')),';'),
  function_declaration: $ => seq(optional('unsafe'),'fn',$._type,field('name',$.function_name),optional($.type_parameters),$.parameters,$.block),
  function_name: $ => seq($.identifier,optional(seq('::',$.identifier))),
  foreign_function_declaration: $ => seq('unsafe','extern','C','fn',$._type,field('name',$.identifier),$.parameters,';'),
  parameters: $ => seq('(',optional(list($.parameter)),')'),
  parameter: $ => seq($._type,field('name',$.identifier)),
  type_parameters: $ => seq('<',list($.identifier),'>'),
  _type: $ => choice($.reference_type,$.pointer_type,$.array_type,$.type_path,$.grouped_type,$.function_type),
  reference_type: $ => prec.right(seq('ref',optional('mut'),$._type)),
  pointer_type: $ => prec.right(seq('ptr',optional('mut'),$._type)),
  array_type: $ => prec.left(2,seq($._type,'[',optional(choice($.number,$.path)),']')),
  grouped_type: $ => seq('(',$._type,')'),
  type_path: $ => prec.right(1,seq($.path,optional($.type_arguments))),
  type_arguments: $ => seq('<',list($._type),'>'),
  function_type: $ => seq('unsafe','extern','C','fn',$._type,'(',optional(list($._type)),')'),
  path: $ => seq($.identifier,repeat(seq('::',$.identifier))),
  block: $ => seq('{',repeat($._statement),optional($._expression),'}'),
  _statement: $ => choice($.binding_statement,$.assignment_statement,$.expression_statement,$.return_statement,$.assert_statement,$.defer_statement,$.discard_statement,$.burn_statement,$.if_expression,$.block,$.unsafe_expression,$.while_statement,$.for_statement,$.break_statement,$.continue_statement,$.region_statement),
  binding_statement: $ => seq($.binding,';'),
  binding: $ => seq(choice('let','var'),optional($._type),field('name',$.identifier),'=',$._expression),
  assignment_statement: $ => seq($.assignment,';'),
  assignment: $ => seq($._expression,choice('=','+=','-=','*=','/=','%=','<<=','>>=','&=','^=','|='),$._expression),
  expression_statement: $ => seq($._expression,';'),
  return_statement: $ => seq('return',optional($._expression),';'),
  assert_statement: $ => seq('assert','(',$._expression,')',';'),
  defer_statement: $ => seq('defer',$._expression,';'),
  discard_statement: $ => seq('discard',$._expression,';'),
  burn_statement: $ => seq('burn',$._expression,';'),
  while_statement: $ => seq('while','(',$._expression,')',$.block),
  for_statement: $ => choice(seq('for','(',optional(choice($.binding,$.assignment)),';',optional($._expression),';',optional($.assignment),')',$.block),seq('for','(','let',$._type,$.identifier,'in',$._expression,')',$.block)),
  break_statement: $ => seq('break',';'),
  continue_statement: $ => seq('continue',';'),
  region_statement: $ => seq('region',$.identifier,'in',$._expression,$.block),
  _expression: $ => choice($.path,$.number,$.string,$.boolean,$.null,$.unary_expression,$.binary_expression,$.cast_expression,$.call_expression,$.generic_call_expression,$.index_expression,$.field_expression,$.propagate_expression,$.grouped_expression,$.array_expression,$.record_expression,$.variant_expression,$.block,$.if_expression,$.switch_expression,$.unsafe_expression),
  unary_expression: $ => prec.right(12,seq(choice('-','+','!','~','*','ref',seq('ref','mut')),$._expression)),
  binary_expression: $ => choice(...[
   [1,['||']],[2,['&&']],[3,['==','!=','<','<=','>','>=']],[4,['|']],[5,['^']],[6,['&']],[7,['<<','>>']],[8,['+','-']],[9,['*','/','%']]
  ].map(([p,ops])=>prec.left(p,seq(field('left',$._expression),field('operator',ops.length===1?ops[0]:choice(...ops)),field('right',$._expression))))),
  cast_expression: $ => prec.left(11,seq($._expression,'as',$._type)),
  call_expression: $ => prec.left(14,seq(field('function',$._expression),$.arguments)),
  generic_call_expression: $ => prec.dynamic(1,seq($.path,$.type_arguments,$.arguments)),
  arguments: $ => seq('(',optional(list($.argument)),')'),
  argument: $ => seq(optional(seq('.',$.identifier,'=')),$._expression),
  index_expression: $ => prec.left(14,seq($._expression,'[',choice($._expression,seq(optional($._expression),'..',optional($._expression))),']')),
  field_expression: $ => prec.left(14,seq($._expression,'.',field('name',$.identifier))),
  propagate_expression: $ => prec.left(14,seq($._expression,'?')),
  grouped_expression: $ => seq('(',$._expression,')'),
  array_expression: $ => seq('[',optional(seq($._expression,choice(seq(';',choice($.number,$.path)),seq(repeat(seq(',',$._expression)),optional(','))))),']'),
  record_expression: $ => seq($.path,optional($.type_arguments),'{',optional(list($.record_field)),'}'),
  record_field: $ => seq('.',field('name',$.identifier),optional(seq('=',$._expression))),
  variant_expression: $ => prec.right(seq('.',$.identifier,optional(seq('{',optional(list($.record_field)),'}')))),
  if_expression: $ => prec.right(seq('if','(',$._expression,')',$.block,optional(seq('else',choice($.block,$.if_expression))))),
  switch_expression: $ => seq('switch','(',$._expression,')','{',repeat($.switch_case),'}'),
  switch_case: $ => seq('case',$.pattern,':',$.block),
  pattern: $ => seq('.',$.identifier,optional(choice(seq('(',$.identifier,')'),seq('{',optional(list($.pattern_field)),'}')))),
  pattern_field: $ => seq('.',$.identifier,'=',$.identifier),
  unsafe_expression: $ => seq('unsafe',$.block),
  identifier: $ => /[A-Za-z_][A-Za-z0-9_]*/,
  number: $ => token(choice(/0x[0-9a-fA-F](_?[0-9a-fA-F])*/,/0b[01](_?[01])*/,/[0-9](_?[0-9])*(\.[0-9](_?[0-9])*)?([eE][+-]?[0-9](_?[0-9])*)?/)),
  string: $ => seq(choice('"','b"','c"'),repeat(choice($.escape_sequence,token.immediate(/[^"\\\r\n]+/))),token.immediate('"')),
  escape_sequence: $ => token.immediate(seq('\\',choice(/[\\"nrt0]/,/x[0-9a-fA-F]{2}/,/u\{[0-9a-fA-F]{1,6}\}/))),
  boolean: $ => choice('true','false'),
  null: $ => 'null',
  line_comment: $ => token(seq('//',/[^\r\n]*/)),
 }
});
