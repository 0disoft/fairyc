"""Package the detached native graph frame; update its pin only explicitly.

Distribution-time source extraction only. The product receives bytes and never
reads Go sources, discovers files, or invokes this tool.
"""
import argparse
import hashlib
from pathlib import Path
import re
import struct

ROOT = Path(__file__).resolve().parent.parent
PIN = ROOT / 'examples/lexer_candidate/src/module_state_graph_frame_pin.fy'
SOURCE = ROOT / 'internal/contractstatenative/graph_native_c.go'


def frame_source():
    source = SOURCE.read_bytes()
    source.decode('utf-8')
    # Match the actual Go raw constant, including its initial/final newline.
    # Go discards CR in raw literals; refuse noncanonical sources rather than
    # silently rewriting them. No comment stripping or whitespace trimming.
    if b'\r' in source or not source.endswith(b'\n'):
        raise ValueError('noncanonical graph frame source')
    matches = list(re.finditer(rb'^const graphNativeFrameC = `([^`]*)`\n?\Z',
                              source, re.MULTILINE))
    if len(matches) != 1:
        raise ValueError('expected one anchored graphNativeFrameC raw constant')
    frame = matches[0].group(1)
    if not frame or not frame.startswith(b'\n') or not frame.endswith(b'\n'):
        raise ValueError('noncanonical graph frame literal')
    return frame


def pack_and_pin():
    frame = frame_source()
    if len(frame) > 8388608:
        raise ValueError('graph frame output exceeds 8MiB')
    header = b'FYCSGRAPHFRAME1\n' + struct.pack('<II', 1, len(frame))
    data = header + frame
    if len(data) > 1048576:
        raise ValueError('graph frame bundle exceeds 1MiB')
    pin = [
        'module module_state_graph_frame_pin;', '',
        '// Generated by tools/package-candidate-state-graph-frame.py --update-pin.',
        '// Exact Go graphNativeFrameC raw value; offsets require size AND SHA256.',
        f'pub fn usize size(){{return {len(data)};}}',
        'pub fn ref u8[] digest(){return b"' + hashlib.sha256(data).hexdigest() + '";}',
        f'pub fn usize content_start(){{return {len(header)};}}',
        f'pub fn usize content_end(){{return {len(data)};}}',
    ]
    return data, '\n'.join(pin) + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path)
    parser.add_argument('--update-pin', action='store_true')
    args = parser.parse_args()
    try:
        data, pin = pack_and_pin()
        if args.update_pin:
            PIN.write_text(pin, encoding='utf-8', newline='\n')
        elif not PIN.is_file() or PIN.read_bytes() != pin.encode('utf-8'):
            parser.error('graph frame pin drift; regenerate explicitly with --update-pin and review')
        if args.output:
            args.output.parent.mkdir(parents=True, exist_ok=True)
            args.output.write_bytes(data)
    except (OSError, ValueError) as error:
        parser.error(str(error))
    print(f'Graph frame assets: 1 section, {len(data)} bytes, SHA256 {hashlib.sha256(data).hexdigest()}')


if __name__ == '__main__':
    main()
