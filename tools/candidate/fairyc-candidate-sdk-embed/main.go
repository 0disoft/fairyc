// Copy the owning compiler SDK bytes into deterministic private Fairy literals.
// All runtime selection/authentication/parsing/identity logic remains in Fairy.
package main

import (
	"bytes"
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/0disoft/fairyc/internal/sdkstdlib"
)

func quoted(input []byte) string {
	var out strings.Builder
	out.WriteString("b\"")
	for _, value := range input {
		switch value {
		case '\n':
			out.WriteString(`\n`)
		case '\r':
			out.WriteString(`\r`)
		case '\t':
			out.WriteString(`\t`)
		case '\\':
			out.WriteString(`\\`)
		case '"':
			out.WriteString(`\"`)
		default:
			if value >= 32 && value < 127 {
				out.WriteByte(value)
			} else {
				fmt.Fprintf(&out, `\x%02x`, value)
			}
		}
	}
	out.WriteByte('"')
	return out.String()
}
func generate() (map[string][]byte, error) {
	definition, err := sdkstdlib.LoadVector()
	if err != nil {
		return nil, err
	}
	names := []string{"alloc", "bytes", "fs", "io", "num", "process", "text", "vec"}
	if len(definition.Sources) != len(names) {
		return nil, fmt.Errorf("review changed SDK source set before generation")
	}
	files := map[string][]byte{}
	for index, source := range definition.Sources {
		name := names[index]
		if source.Path != "std/"+name+".fy" || source.Module.Path != "std::"+name {
			return nil, fmt.Errorf("unexpected SDK source %q", source.Path)
		}
		origin := "sources/" + source.Path
		if name == "vec" {
			origin = "sources/optional/" + source.Path
		}
		for start, part := 0, 0; start < len(source.Bytes); start, part = start+16384, part+1 {
			end := min(start+16384, len(source.Bytes))
			module := fmt.Sprintf("project_sdk_data_%s_%d", name, part)
			var out strings.Builder
			fmt.Fprintf(&out, "module %s;\nimport std::bytes as bytes;\nimport project_path as work;\n\n// Generated by tools/candidate/fairyc-candidate-sdk-embed; original authority: internal/sdkstdlib/%s.\n// SDK %s; language %s; ABI %s.\n// Do not edit byte literals. Regenerate, then authenticate against sdk_authority.\npub fn u32 append(ref mut bytes::Buffer output,ref mut usize meter){\n", module, origin, sdkstdlib.SDKIdentity, sdkstdlib.LanguageRevision, sdkstdlib.RuntimeABI)
			for at := start; at < end; at += 2048 {
				finish := min(at+2048, end)
				fmt.Fprintf(&out, "    if(!work::charge(meter,%d)){return 5;}if(!bytes::append(output,%s).is_ok){return 4;}\n", finish-at+1, quoted(source.Bytes[at:finish]))
			}
			out.WriteString("    return 0;\n}\n")
			body := []byte(out.String())
			if len(body) > 40000 {
				return nil, fmt.Errorf("generated part exceeds 40 kB: %s", module)
			}
			files[module+".fy"] = body
		}
	}
	return files, nil
}
func run(args []string) error {
	if len(args) != 2 || args[0] != "--write" && args[0] != "--check" {
		return fmt.Errorf("usage: sdk-embed (--write|--check) source-directory")
	}
	dir, err := filepath.Abs(args[1])
	if err != nil {
		return err
	}
	files, err := generate()
	if err != nil {
		return err
	}
	existing, err := filepath.Glob(filepath.Join(dir, "project_sdk_data_*.fy"))
	if err != nil {
		return err
	}
	for _, path := range existing {
		if _, ok := files[filepath.Base(path)]; !ok {
			return fmt.Errorf("unexpected stale generated file: %s", path)
		}
	}
	for name, body := range files {
		path := filepath.Join(dir, name)
		if args[0] == "--write" {
			if err := os.WriteFile(path, body, 0600); err != nil {
				return err
			}
		} else {
			actual, err := os.ReadFile(path)
			if err != nil {
				return err
			}
			if !bytes.Equal(actual, body) {
				return fmt.Errorf("embedded SDK data differs from owning source: %s", path)
			}
		}
	}
	fmt.Printf("PASS: %d exact SDK literal parts %s\n", len(files), args[0])
	return nil
}
func main() {
	if err := run(os.Args[1:]); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
