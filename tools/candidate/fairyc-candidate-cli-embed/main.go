// Embed the owning CLI contract and metadata as data, without a runtime Go frontend.
package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"strconv"
	"strings"

	"github.com/0disoft/fairyc/internal/diagnostic"
	"github.com/0disoft/fairyc/internal/sdkstdlib"
	"github.com/0disoft/fairyc/internal/target"
)

func generate() ([]byte, error) {
	file, err := parser.ParseFile(token.NewFileSet(), "internal/cli/run.go", nil, 0)
	if err != nil {
		return nil, err
	}
	var usage string
	ast.Inspect(file, func(node ast.Node) bool {
		spec, ok := node.(*ast.ValueSpec)
		if ok && len(spec.Names) == 1 && spec.Names[0].Name == "usage" && len(spec.Values) == 1 {
			if literal, ok := spec.Values[0].(*ast.BasicLit); ok {
				usage, err = strconv.Unquote(literal.Value)
			}
		}
		return true
	})
	if err != nil || usage == "" {
		return nil, fmt.Errorf("cannot read owning CLI usage: %v", err)
	}
	var out strings.Builder
	out.WriteString("module public_cli_data;\nimport std::bytes as bytes;\n\n// Generated by tools/candidate/fairyc-candidate-cli-embed from internal/cli, diagnostic,\n// target, and sdkstdlib. Build tools replace version() in an isolated copy with\n// current source-build metadata; an unstamped direct build retains unknown VCS.\n")
	put := func(name, value string) {
		fmt.Fprintf(&out, "pub fn ref str %s(){return %s;}\n", name, strconv.Quote(value))
	}
	put("help", usage)
	put("version", fmt.Sprintf("Fairy C Stage 0\ncompiler: development\nsdk: %s %s\nlanguage: %s\nruntime: %s\nrevision: unknown\nmodified: unknown\n", sdkstdlib.SDKIdentity, sdkstdlib.Version, sdkstdlib.LanguageRevision, sdkstdlib.RuntimeABI))
	var report strings.Builder
	for i, spec := range target.All() {
		if err := target.Validate(spec); err != nil {
			return nil, err
		}
		if i > 0 {
			report.WriteByte('\n')
		}
		yesNo := func(b bool) string {
			if b {
				return "yes"
			}
			return "no"
		}
		fmt.Fprintf(&report, "%s\n  schema: %s\n  emission subset: %s\n  emittable: %s\n  conformant: %s\n  supported: %s\n  missing evidence:\n", spec.ID, spec.SchemaVersion, spec.Evidence.EmissionSubset, yesNo(spec.Evidence.Emittable), yesNo(spec.Evidence.Conformant), yesNo(spec.Evidence.Supported))
		for _, missing := range spec.Evidence.Missing {
			fmt.Fprintf(&report, "    - %s\n", missing)
		}
	}
	put("targets", report.String())
	out.WriteString("pub fn ref str explanation(ref u8[] code){\n")
	for _, entry := range diagnostic.CatalogEntries() {
		text := fmt.Sprintf("%s: %s\nCategory: %s\nCatalog: %s (provisional Stage 0)\n", entry.Code, entry.Meaning, entry.Category, diagnostic.CatalogVersion)
		fmt.Fprintf(&out, "    if(bytes::equal(code,b%s)){return %s;}\n", strconv.Quote(entry.Code), strconv.Quote(text))
	}
	out.WriteString("    return \"\";\n}\n")
	if out.Len() > 40000 {
		return nil, fmt.Errorf("CLI metadata exceeds 40 kB: %d", out.Len())
	}
	return []byte(out.String()), nil
}
func run(args []string) error {
	if len(args) != 2 || args[0] != "--write" && args[0] != "--check" {
		return fmt.Errorf("usage: cli-embed (--write|--check) source-directory")
	}
	body, err := generate()
	if err != nil {
		return err
	}
	path := filepath.Join(args[1], "public_cli_data.fy")
	if args[0] == "--write" {
		if err = os.WriteFile(path, body, 0600); err != nil {
			return err
		}
	} else {
		current, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		if !bytes.Equal(body, current) {
			return fmt.Errorf("stale CLI metadata: %s", path)
		}
	}
	fmt.Printf("PASS: exact CLI metadata %s (%d bytes)\n", args[0], len(body))
	return nil
}
func main() {
	if err := run(os.Args[1:]); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
