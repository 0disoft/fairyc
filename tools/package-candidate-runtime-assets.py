"""Build the private, hash-pinned runtime source pack from authoritative C files.

The pack is a compiler distribution asset, never a source-discovery path. Copy
it with the matching compiler. Updating C requires explicit pin regeneration.
"""
import argparse
import hashlib
from pathlib import Path
import struct

ROOT = Path(__file__).resolve().parent.parent
SOURCES = [
    'internal/cruntime/stage0_scalar.c',
    'internal/cruntime/stage0_windows_trap_receipt.inc',
    'internal/cstdlib/stage0_windows_console.c',
    'internal/cstdlib/stage0_windows_file.c',
    'internal/cstdlib/stage0_windows_file_portable.c',
    'internal/cstdlib/stage0_windows_file_metadata.c',
    'internal/cstdlib/stage0_windows_file_link.c',
    'internal/cstdlib/stage0_windows_file_remove_tree.c',
    'internal/cstdlib/stage0_windows_directory.c',
    'internal/cstdlib/stage0_windows_process_args.c',
    'internal/cstdlib/stage0_system_heap.c',
    'internal/cstdlib/stage0_byte_compare.c',
    'internal/cstdlib/stage0_buffer.c',
    'internal/cstdlib/stage0_windows_file_buffer.c',
    'internal/cstdlib/stage0_arena.c',
    'internal/cstdlib/stage0_text_view.c',
    'internal/cstdlib/stage0_owned_text.c',
    'internal/cstdlib/stage0_vector_storage.c',
    'internal/candidatehost/windows_process.c',
    'internal/candidatehost/windows_rooted_file.c',
    'internal/cstdlib/stage0_windows_path.inc',
]
PIN = ROOT / 'examples/lexer_candidate/src/native_runtime_asset_pin.fy'


def pack_and_pin():
    data = bytearray(b'FYCRUNTIMEASSETS1\n')
    data.extend(struct.pack('<I', len(SOURCES)))
    spans = []
    for name in SOURCES:
        raw = (ROOT / name).read_bytes()
        if not raw or b'\r' in raw or not raw.endswith(b'\n'):
            raise ValueError(f'noncanonical runtime source: {name}')
        data.extend(struct.pack('<I', len(raw)))
        start = len(data)
        data.extend(raw)
        spans.append((start, len(data)))
    assert len(data) <= 1048576
    pin = ['module native_runtime_asset_pin;', '',
           '// Generated by tools/package-candidate-runtime-assets.py --update-pin.',
           '// Raw source authority and order: SOURCES in that tool; never edit offsets.',
           f'pub fn usize count(){{return {len(SOURCES)};}}',
           f'pub fn usize size(){{return {len(data)};}}',
           'pub fn ref u8[] digest(){return b"' + hashlib.sha256(data).hexdigest() + '";}',
           'pub fn usize start(usize id){']
    pin += [f'    if(id=={i}){{return {a};}} // {SOURCES[i-1]}'
            for i, (a, _) in enumerate(spans, 1)]
    pin += ['    return 0;', '}', 'pub fn usize end(usize id){']
    pin += [f'    if(id=={i}){{return {b};}}' for i, (_, b) in enumerate(spans, 1)]
    pin += ['    return 0;', '}', '']
    return bytes(data), '\n'.join(pin)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path)
    parser.add_argument('--update-pin', action='store_true')
    args = parser.parse_args()
    data, pin = pack_and_pin()
    if args.update_pin:
        PIN.write_text(pin, encoding='utf-8', newline='\n')
    elif PIN.read_text(encoding='utf-8') != pin:
        parser.error('runtime sources changed; regenerate and review the compiler pin')
    if args.output:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_bytes(data)
    print(f'Runtime assets: {len(SOURCES)} sources, {len(data)} bytes, SHA256 {hashlib.sha256(data).hexdigest()}')


if __name__ == '__main__':
    main()
