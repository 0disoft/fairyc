"""Materialize the Linux companion's exact stdlib symbol table from its Go owner."""
import argparse
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / 'examples/lexer_candidate/src/linux_runtime_contract.fy'
# This is the Linux-only projection of cstdlibcontract.componentLinkOrder.
COMPONENTS = ('LinuxConsole', 'LinuxFile', 'SystemHeap', 'ByteCompare', 'Buffer',
              'LinuxFileBuffer', 'Arena', 'TextView', 'LinuxProcessArgs', 'OwnedText')
DEPENDENCIES = {'Buffer': ('SystemHeap',), 'Arena': ('SystemHeap',),
                'LinuxProcessArgs': ('TextView',),
                'LinuxFileBuffer': ('LinuxFile', 'SystemHeap', 'Buffer'),
                'OwnedText': ('SystemHeap', 'Buffer', 'TextView')}


def source():
    owner = (ROOT / 'internal/cstdlibcontract/contract.go').read_text(encoding='utf-8')
    table = owner.split('var symbolComponents = map[string]Component{', 1)[1].split('\n}', 1)[0]
    pairs = re.findall(r'"([A-Za-z0-9_]+)":\s+Component([A-Za-z0-9]+),', table)
    if len(pairs) != table.count(':') or set(part for _, part in pairs) != set(COMPONENTS):
        raise ValueError('stdlib table shape/component set changed; review the Linux contract')
    order = owner.split('var componentLinkOrder = []Component{', 1)[1].split('\n}', 1)[0]
    projected = tuple(name for name in re.findall(r'Component([A-Za-z0-9]+),', order)
                      if name in COMPONENTS)
    if projected != COMPONENTS:
        raise ValueError('Linux link order changed; review the component projection')
    lines = ['module linux_runtime_contract;', 'import std::bytes as bytes;', '',
             '// Generated by tools/generate-candidate-linux-runtime-contract.py.',
             '// Authority: internal/cstdlibcontract/contract.go. IDs are Linux-local.',
             'pub fn u32 component(ref u8[] name){']
    for symbol, component in sorted(pairs):
        lines.append(f'    if(bytes::equal(name,b"{symbol}")){{return {COMPONENTS.index(component)+1};}}')
    lines += ['    return 0;', '}', 'pub fn u32 closure(u32 id){']
    for index, component in enumerate(COMPONENTS, 1):
        bits = 1 << (index - 1)
        for dependency in DEPENDENCIES.get(component, ()):
            bits |= 1 << COMPONENTS.index(dependency)
        lines.append(f'    if(id=={index}){{return {bits};}}')
    lines += ['    return 0;', '}', '']
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--update', action='store_true')
    args = parser.parse_args()
    expected = source()
    if args.update:
        OUTPUT.write_text(expected, encoding='utf-8', newline='\n')
    elif OUTPUT.read_text(encoding='utf-8') != expected:
        parser.error('Linux runtime contract changed; regenerate and review with --update')
    print('Linux companion stdlib contract matches its source owner')


if __name__ == '__main__':
    main()
