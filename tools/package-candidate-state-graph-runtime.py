"""Package the explicit, private graph runtime asset; regenerate pins only on request.

This distribution-time tool mirrors internal/cstdlib/contract_state_graph.go and
contract_state_overlay.go. Product code receives the bundle bytes explicitly.
It neither discovers sources nor starts this tool (or Go).
"""
import argparse
import hashlib
from pathlib import Path
import struct

ROOT = Path(__file__).resolve().parent.parent
PIN = ROOT / 'examples/lexer_candidate/src/module_state_graph_native_asset_pin.fy'
SOURCES = (
    'stage0_contract_state_overlay.h',
    'stage0_contract_state_overlay.c',
    'stage0_contract_state_graph.h',
    'stage0_contract_state_graph.c',
    'stage0_contract_state_graph_key.c',
)


def canonical_source(name):
    # canonicalSource is validation only, including the Go build comment. Do
    # not strip comments, normalize CRLF, or trim the trailing newline.
    raw = (ROOT / 'internal/cstdlib' / name).read_bytes()
    if not raw or b'\r' in raw or not raw.endswith(b'\n'):
        raise ValueError(f'noncanonical graph runtime source: {name}')
    return raw


def pack_and_pin():
    overlay_h, overlay_c, graph_h, graph_c, key_c = map(canonical_source, SOURCES)
    overlay_include = b'#include "stage0_contract_state_overlay.h"'
    graph_include = b'#include "stage0_contract_state_graph.h"'
    declarations = graph_h.replace(overlay_include, overlay_h, 1)
    overlay = overlay_c.replace(overlay_include, overlay_h, 1)
    runtime = (overlay + b'\n' + graph_c.replace(graph_include, declarations, 1)
               + b'\n' + key_c.replace(graph_include, declarations, 1))
    data = bytearray(b'FYCSGRAPHRUNTIME1\n')
    data.extend(struct.pack('<I', 2))
    spans = []
    for part in (declarations, runtime):
        if len(part) > 8388608:
            raise ValueError('graph runtime output exceeds 8MiB')
        data.extend(struct.pack('<I', len(part)))
        start = len(data)
        data.extend(part)
        spans.append((start, len(data)))
    if len(data) > 1048576:
        raise ValueError('graph runtime bundle exceeds 1MiB')
    pin = [
        'module module_state_graph_native_asset_pin;', '',
        '// Generated by tools/package-candidate-state-graph-runtime.py --update-pin.',
        '// Exact cstdlib graph declarations/runtime; offsets require size AND SHA256.',
        f'pub fn usize size(){{return {len(data)};}}',
        'pub fn ref u8[] digest(){return b"' + hashlib.sha256(data).hexdigest() + '";}',
    ]
    for name, (start, end) in zip(('declarations', 'runtime'), spans):
        pin += [f'pub fn usize {name}_start(){{return {start};}}',
                f'pub fn usize {name}_end(){{return {end};}}']
    return bytes(data), '\n'.join(pin) + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path)
    parser.add_argument('--update-pin', action='store_true')
    args = parser.parse_args()
    try:
        data, pin = pack_and_pin()
        if args.update_pin:
            PIN.write_text(pin, encoding='utf-8', newline='\n')
        elif not PIN.is_file() or PIN.read_text(encoding='utf-8') != pin:
            parser.error('graph runtime pin drift; regenerate explicitly with --update-pin and review')
        if args.output:
            args.output.parent.mkdir(parents=True, exist_ok=True)
            args.output.write_bytes(data)
    except (OSError, ValueError) as error:
        parser.error(str(error))
    print(f'Graph runtime assets: 2 sections, {len(data)} bytes, SHA256 {hashlib.sha256(data).hexdigest()}')


if __name__ == '__main__':
    main()
