package contractabi

import (
	"fmt"
	"strconv"
	"strings"
)

// RenderTypeScript emits codec-neutral clients. The generated transport owns chain selection,
// serialization, transaction signing, and response decoding while method signatures retain the IDL
// types.
func RenderTypeScript(document Document) ([]byte, error) {
	if err := validateDocument(document); err != nil {
		return nil, err
	}
	if err := validateTypeScriptBindingNames(document); err != nil {
		return nil, err
	}
	facts := inspectDocumentTypes(document)
	events := make(map[string]string, len(document.Events))
	for _, event := range document.Events {
		events[event.Name] = exportedName(event.Name) + "Event"
	}

	var builder strings.Builder
	builder.WriteString("// Code generated by fairyc-contract-idl. DO NOT EDIT.\n")
	builder.WriteString("// Schema: ")
	builder.WriteString(SchemaVersion)
	builder.WriteString("\n\n")
	builder.WriteString("export interface ContractCallRequest {\n")
	builder.WriteString("  readonly contract: string;\n")
	builder.WriteString("  readonly method: string;\n")
	builder.WriteString("  readonly args: readonly unknown[];\n")
	builder.WriteString("  readonly view: boolean;\n")
	builder.WriteString("  readonly payable: boolean;\n")
	builder.WriteString("  readonly effects: readonly [\"external_call\"];\n")
	builder.WriteString("  readonly value?: unknown;\n")
	builder.WriteString("}\n\n")
	builder.WriteString("export interface ContractTransport {\n")
	builder.WriteString("  call<T>(request: ContractCallRequest): Promise<T>;\n")
	builder.WriteString("}\n")
	if facts.usesPayable {
		builder.WriteString("\nexport interface PayableCallOptions {\n")
		builder.WriteString("  readonly value: unknown;\n")
		builder.WriteString("}\n")
	}
	if facts.usesOption {
		builder.WriteString("\nexport type Option<T> = T | null;\n")
	}
	if facts.usesResult {
		builder.WriteString("\nexport type Result<T, E> =\n")
		builder.WriteString("  | Readonly<{ ok: true; value: T }>\n")
		builder.WriteString("  | Readonly<{ ok: false; error: E }>;\n")
	}
	for _, path := range facts.externalTypes {
		name := externalTypeName(path)
		builder.WriteString("\nexport type ")
		builder.WriteString(name)
		builder.WriteString(" = Readonly<{\n")
		builder.WriteString("  readonly __fairyType: ")
		builder.WriteString(strconv.Quote(path))
		builder.WriteString(";\n  readonly value: unknown;\n}>;\n")
	}
	for _, event := range document.Events {
		builder.WriteString("\nexport interface ")
		builder.WriteString(events[event.Name])
		builder.WriteString(" {\n")
		for _, field := range event.Fields {
			fieldType, err := renderTypeScriptType(field.Type, events)
			if err != nil {
				return nil, err
			}
			builder.WriteString("  readonly ")
			builder.WriteString(tsLocalName(field.Name))
			builder.WriteString(": ")
			builder.WriteString(fieldType)
			builder.WriteString(";\n")
		}
		builder.WriteString("}\n")
	}
	for _, contract := range document.Contracts {
		clientName := exportedName(contract.Name) + "Client"
		builder.WriteString("\nexport class ")
		builder.WriteString(clientName)
		builder.WriteString(" {\n")
		builder.WriteString("  public constructor(private readonly transport: ContractTransport) {}\n")
		for _, function := range contract.Functions {
			parameterNames := allocateTypeScriptParameterNames(function.Parameters, function.Payable)
			resultType, err := renderTypeScriptType(function.Result, events)
			if err != nil {
				return nil, err
			}
			builder.WriteString("\n  public ")
			builder.WriteString(tsLocalName(function.Name))
			builder.WriteString("(")
			for index, parameter := range function.Parameters {
				if index > 0 {
					builder.WriteString(", ")
				}
				parameterType, typeErr := renderTypeScriptType(parameter.Type, events)
				if typeErr != nil {
					return nil, typeErr
				}
				builder.WriteString(parameterNames[index])
				builder.WriteString(": ")
				builder.WriteString(parameterType)
			}
			if function.Payable {
				if len(function.Parameters) > 0 {
					builder.WriteString(", ")
				}
				builder.WriteString("options: PayableCallOptions")
			}
			builder.WriteString("): Promise<")
			builder.WriteString(resultType)
			builder.WriteString("> {\n")
			builder.WriteString("    return this.transport.call<")
			builder.WriteString(resultType)
			builder.WriteString(">({\n")
			builder.WriteString("      contract: ")
			builder.WriteString(strconv.Quote(contract.Name))
			builder.WriteString(",\n      method: ")
			builder.WriteString(strconv.Quote(function.Name))
			builder.WriteString(",\n      args: [")
			for index := range function.Parameters {
				if index > 0 {
					builder.WriteString(", ")
				}
				builder.WriteString(parameterNames[index])
			}
			builder.WriteString("],\n      view: ")
			builder.WriteString(strconv.FormatBool(function.View))
			builder.WriteString(",\n      payable: ")
			builder.WriteString(strconv.FormatBool(function.Payable))
			builder.WriteString(",\n      effects: [\"external_call\"]")
			if function.Payable {
				builder.WriteString(",\n      value: options.value")
			}
			builder.WriteString(",\n    });\n  }\n")
		}
		builder.WriteString("}\n")
	}
	return []byte(builder.String()), nil
}

func renderTypeScriptType(value Type, events map[string]string) (string, error) {
	switch value.Kind {
	case TypeArray:
		if value.Element == nil || value.Length == nil {
			return "", fmt.Errorf("invalid array type")
		}
		element, err := renderTypeScriptType(*value.Element, events)
		if err != nil {
			return "", err
		}
		return fmt.Sprintf("ReadonlyArray<%s> & Readonly<{ length: %d }>", element, *value.Length), nil
	case TypeNamed:
		switch value.Name {
		case "void":
			return "void", nil
		case "bool":
			return "boolean", nil
		case "u8", "u16", "u32", "i8", "i16", "i32":
			return "number", nil
		case "u64", "u128", "u256", "i64", "i128":
			return "bigint", nil
		case "String":
			return "string", nil
		case "Bytes":
			return "Uint8Array", nil
		case "Option":
			if len(value.Arguments) != 1 {
				return "", fmt.Errorf("invalid Option type")
			}
			argument, err := renderTypeScriptType(value.Arguments[0], events)
			if err != nil {
				return "", err
			}
			return "Option<" + argument + ">", nil
		case "Result":
			if len(value.Arguments) != 2 {
				return "", fmt.Errorf("invalid Result type")
			}
			okType, err := renderTypeScriptType(value.Arguments[0], events)
			if err != nil {
				return "", err
			}
			errType, err := renderTypeScriptType(value.Arguments[1], events)
			if err != nil {
				return "", err
			}
			return "Result<" + okType + ", " + errType + ">", nil
		default:
			if eventName, found := events[value.Name]; found {
				return eventName, nil
			}
			return externalTypeName(value.Name), nil
		}
	default:
		return "", fmt.Errorf("unsupported TypeScript ABI type %s", value.String())
	}
}
