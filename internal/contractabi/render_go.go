package contractabi

import (
	"fmt"
	"go/format"
	"strconv"
	"strings"
)

// RenderGo emits codec-neutral clients for the requested Go package. The generated transport owns
// chain selection, serialization, transaction signing, and response decoding.
func RenderGo(document Document, packageName string) ([]byte, error) {
	if err := validateDocument(document); err != nil {
		return nil, err
	}
	if err := ValidateGoPackageName(packageName); err != nil {
		return nil, err
	}
	if err := validateGoBindingNames(document); err != nil {
		return nil, err
	}
	facts := inspectDocumentTypes(document)
	events := make(map[string]string, len(document.Events))
	for _, event := range document.Events {
		events[event.Name] = exportedName(event.Name) + "Event"
	}

	var builder strings.Builder
	builder.WriteString("// Code generated by fairyc-contract-idl. DO NOT EDIT.\n")
	builder.WriteString("// Schema: ")
	builder.WriteString(SchemaVersion)
	builder.WriteString("\n\npackage ")
	builder.WriteString(packageName)
	builder.WriteString("\n\nimport \"context\"\n\n")
	builder.WriteString("type ContractCallRequest struct {\n")
	builder.WriteString("\tContract string\n\tMethod string\n\tArguments []any\n\tView bool\n\tPayable bool\n\tEffects []string\n\tValue any\n}\n\n")
	builder.WriteString("type ContractTransport interface {\n")
	builder.WriteString("\tCall(context.Context, ContractCallRequest, any) error\n}\n")
	if facts.usesPayable {
		builder.WriteString("\ntype PayableCallOptions struct {\n\tValue any\n}\n")
	}
	if facts.usesOption {
		builder.WriteString("\ntype FairyOption[T any] struct {\n\tValue T\n\tSome bool\n}\n")
	}
	if facts.usesResult {
		builder.WriteString("\ntype FairyResult[T, E any] struct {\n\tValue T\n\tError E\n\tOK bool\n}\n")
	}
	if facts.usesU128 {
		builder.WriteString("\ntype FairyU128 [16]byte\n")
	}
	if facts.usesU256 {
		builder.WriteString("\ntype FairyU256 [32]byte\n")
	}
	if facts.usesI128 {
		builder.WriteString("\ntype FairyI128 [16]byte\n")
	}
	for _, path := range facts.externalTypes {
		builder.WriteString("\ntype ")
		builder.WriteString(externalTypeName(path))
		builder.WriteString(" struct {\n\tValue any\n}\n")
	}
	for _, event := range document.Events {
		builder.WriteString("\ntype ")
		builder.WriteString(events[event.Name])
		builder.WriteString(" struct {\n")
		for _, field := range event.Fields {
			fieldType, err := renderGoType(field.Type, events, false)
			if err != nil {
				return nil, err
			}
			builder.WriteString("\t")
			builder.WriteString(exportedName(field.Name))
			builder.WriteString(" ")
			builder.WriteString(fieldType)
			builder.WriteString("\n")
		}
		builder.WriteString("}\n")
	}
	for _, contract := range document.Contracts {
		clientName := exportedName(contract.Name) + "Client"
		builder.WriteString("\ntype ")
		builder.WriteString(clientName)
		builder.WriteString(" struct {\n\ttransport ContractTransport\n}\n\n")
		builder.WriteString("func New")
		builder.WriteString(clientName)
		builder.WriteString("(transport ContractTransport) *")
		builder.WriteString(clientName)
		builder.WriteString(" {\n\treturn &")
		builder.WriteString(clientName)
		builder.WriteString("{transport: transport}\n}\n")
		for _, function := range contract.Functions {
			parameterNames := allocateGoParameterNames(function.Parameters, function.Payable)
			resultType, err := renderGoType(function.Result, events, true)
			if err != nil {
				return nil, err
			}
			builder.WriteString("\nfunc (client *")
			builder.WriteString(clientName)
			builder.WriteString(") ")
			builder.WriteString(exportedName(function.Name))
			builder.WriteString("(ctx context.Context")
			for index, parameter := range function.Parameters {
				parameterType, typeErr := renderGoType(parameter.Type, events, false)
				if typeErr != nil {
					return nil, typeErr
				}
				builder.WriteString(", ")
				builder.WriteString(parameterNames[index])
				builder.WriteString(" ")
				builder.WriteString(parameterType)
			}
			if function.Payable {
				builder.WriteString(", options PayableCallOptions")
			}
			builder.WriteString(") ")
			if function.Result.Kind == TypeNamed && function.Result.Name == "void" {
				builder.WriteString("error")
			} else {
				builder.WriteString("(")
				builder.WriteString(resultType)
				builder.WriteString(", error)")
			}
			builder.WriteString(" {\n")
			builder.WriteString("\trequest := ContractCallRequest{\n")
			builder.WriteString("\t\tContract: ")
			builder.WriteString(strconv.Quote(contract.Name))
			builder.WriteString(",\n\t\tMethod: ")
			builder.WriteString(strconv.Quote(function.Name))
			builder.WriteString(",\n\t\tArguments: []any{")
			for index := range function.Parameters {
				if index > 0 {
					builder.WriteString(", ")
				}
				builder.WriteString(parameterNames[index])
			}
			builder.WriteString("},\n\t\tView: ")
			builder.WriteString(strconv.FormatBool(function.View))
			builder.WriteString(",\n\t\tPayable: ")
			builder.WriteString(strconv.FormatBool(function.Payable))
			builder.WriteString(",\n\t\tEffects: []string{\"external_call\"},\n")
			if function.Payable {
				builder.WriteString("\t\tValue: options.Value,\n")
			}
			builder.WriteString("\t}\n")
			if function.Result.Kind == TypeNamed && function.Result.Name == "void" {
				builder.WriteString("\treturn client.transport.Call(ctx, request, nil)\n")
			} else {
				builder.WriteString("\tvar result ")
				builder.WriteString(resultType)
				builder.WriteString("\n\terr := client.transport.Call(ctx, request, &result)\n\treturn result, err\n")
			}
			builder.WriteString("}\n")
		}
	}

	formatted, err := format.Source([]byte(builder.String()))
	if err != nil {
		return nil, fmt.Errorf("format generated Go bindings: %w", err)
	}
	return formatted, nil
}

func renderGoType(value Type, events map[string]string, allowVoid bool) (string, error) {
	switch value.Kind {
	case TypeArray:
		if value.Element == nil || value.Length == nil {
			return "", fmt.Errorf("invalid array type")
		}
		element, err := renderGoType(*value.Element, events, false)
		if err != nil {
			return "", err
		}
		return fmt.Sprintf("[%d]%s", *value.Length, element), nil
	case TypeNamed:
		switch value.Name {
		case "void":
			if allowVoid {
				return "struct{}", nil
			}
			return "", fmt.Errorf("void is not a Go value type")
		case "bool":
			return "bool", nil
		case "u8":
			return "uint8", nil
		case "u16":
			return "uint16", nil
		case "u32":
			return "uint32", nil
		case "u64":
			return "uint64", nil
		case "u128":
			return "FairyU128", nil
		case "u256":
			return "FairyU256", nil
		case "i8":
			return "int8", nil
		case "i16":
			return "int16", nil
		case "i32":
			return "int32", nil
		case "i64":
			return "int64", nil
		case "i128":
			return "FairyI128", nil
		case "String":
			return "string", nil
		case "Bytes":
			return "[]byte", nil
		case "Option":
			if len(value.Arguments) != 1 {
				return "", fmt.Errorf("invalid Option type")
			}
			argument, err := renderGoType(value.Arguments[0], events, false)
			if err != nil {
				return "", err
			}
			return "FairyOption[" + argument + "]", nil
		case "Result":
			if len(value.Arguments) != 2 {
				return "", fmt.Errorf("invalid Result type")
			}
			okType, err := renderGoType(value.Arguments[0], events, true)
			if err != nil {
				return "", err
			}
			errType, err := renderGoType(value.Arguments[1], events, false)
			if err != nil {
				return "", err
			}
			return "FairyResult[" + okType + ", " + errType + "]", nil
		default:
			if eventName, found := events[value.Name]; found {
				return eventName, nil
			}
			return externalTypeName(value.Name), nil
		}
	default:
		return "", fmt.Errorf("unsupported Go ABI type %s", value.String())
	}
}

// ValidateGoPackageName rejects package spellings that would make generated Go source invalid.
func ValidateGoPackageName(value string) error {
	if value == "" || len(value) > 128 || !isASCIILower(value[0]) {
		return fmt.Errorf("invalid Go package name %q", value)
	}
	for index := 1; index < len(value); index++ {
		current := value[index]
		if !isASCIILower(current) && (current < '0' || current > '9') && current != '_' {
			return fmt.Errorf("invalid Go package name %q", value)
		}
	}
	if _, reserved := goReserved[value]; reserved {
		return fmt.Errorf("invalid Go package name %q", value)
	}
	return nil
}

func isASCIILower(value byte) bool {
	return value >= 'a' && value <= 'z'
}
